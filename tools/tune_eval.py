"""Fit ChessBot hand-crafted evaluation scales with a documented Texel-style loss."""
from __future__ import annotations

import argparse
import csv
import json
import math
import shutil
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from generate_dataset import COMPONENTS


DEFAULT_SLOPE = math.log(10) / 400


def load_rows(path: Path) -> list[dict[str, object]]:
    if path.suffix.lower() == ".parquet":
        try:
            import pandas as pd
        except ImportError as error:
            raise RuntimeError("Parquet input requires pip install -e '.[analysis]'") from error
        return pd.read_parquet(path).to_dict("records")
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def load_parameters(path: Path) -> dict[str, int | str]:
    parameters: dict[str, int | str] = dict.fromkeys(COMPONENTS, 1000)
    parameters["calibration"] = 1000
    parameters["version"] = "hce-default-v1"
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or key not in parameters:
            raise ValueError(f"invalid reference parameter line: {raw_line}")
        parameters[key] = value if key == "version" else int(value)
    return parameters


def arrays(rows: list[dict[str, object]], split: str) -> tuple[np.ndarray, np.ndarray]:
    selected = [row for row in rows if row["split"] == split]
    if not selected:
        raise ValueError(f"dataset has no {split} rows")
    x = np.asarray([[float(row[name]) for name in COMPONENTS] for row in selected], dtype=float)
    y = np.asarray([float(row["result_stm"]) for row in selected], dtype=float)
    return x, y


def sigmoid(values: np.ndarray) -> np.ndarray:
    return 1 / (1 + np.exp(-np.clip(values, -30, 30)))


def calibrate(scores: np.ndarray, targets: np.ndarray) -> float:
    slope = DEFAULT_SLOPE
    for _ in range(80):
        probabilities = sigmoid(scores * slope)
        gradient = np.mean((probabilities - targets) * scores)
        hessian = np.mean(probabilities * (1 - probabilities) * scores * scores) + 1e-12
        updated = float(np.clip(slope - gradient / hessian, 1e-5, 0.1))
        if abs(updated - slope) < 1e-10:
            break
        slope = updated
    return slope


def metrics(x: np.ndarray, y: np.ndarray, weights: np.ndarray, slope: float) -> dict[str, float]:
    probability = np.clip(sigmoid((x @ weights) * slope), 1e-9, 1 - 1e-9)
    loss = -np.mean(y * np.log(probability) + (1 - y) * np.log(1 - probability))
    return {"log_loss": float(loss), "brier": float(np.mean((probability - y) ** 2)),
            "mean_probability": float(np.mean(probability)), "mean_target": float(np.mean(y))}


def fit(x: np.ndarray, y: np.ndarray, slope: float, iterations: int,
        learning_rate: float, regularization: float) -> np.ndarray:
    weights = np.ones(x.shape[1])
    first = np.zeros_like(weights)
    second = np.zeros_like(weights)
    for iteration in range(1, iterations + 1):
        probabilities = sigmoid((x @ weights) * slope)
        gradient = slope * (x.T @ (probabilities - y)) / len(y)
        gradient += regularization * (weights - 1)
        first = 0.9 * first + 0.1 * gradient
        second = 0.999 * second + 0.001 * gradient * gradient
        corrected_first = first / (1 - 0.9 ** iteration)
        corrected_second = second / (1 - 0.999 ** iteration)
        weights -= learning_rate * corrected_first / (np.sqrt(corrected_second) + 1e-8)
        weights = np.clip(weights, 0, 4)
    return weights


def write_parameters(path: Path, version: str, relative_weights: np.ndarray, slope: float,
                     reference: dict[str, int | str]) -> dict[str, int]:
    absolute = {name: round(int(reference[name]) * float(weight))
                for name, weight in zip(COMPONENTS, relative_weights, strict=True)}
    values = [f"version={version}"]
    values += [f"{name}={absolute[name]}" for name in COMPONENTS]
    values.append(f"calibration={round(slope / DEFAULT_SLOPE * 1000)}")
    path.write_text("# Generated by tools/tune_eval.py; component values are per mille.\n" +
                    "\n".join(values) + "\n", encoding="utf-8")
    return absolute


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--reference", type=Path,
                        default=Path("data/evaluation/hce-default-v1.params"))
    parser.add_argument("--version")
    parser.add_argument("--iterations", type=int, default=2000)
    parser.add_argument("--learning-rate", type=float, default=0.02)
    parser.add_argument("--regularization", type=float, default=0.002)
    args = parser.parse_args()
    if args.iterations < 1 or args.learning_rate <= 0 or args.regularization < 0:
        parser.error("invalid optimizer parameters")
    rows = load_rows(args.dataset)
    reference_parameters = load_parameters(args.reference)
    dataset_versions = {str(row["evaluation_version"]) for row in rows}
    if dataset_versions != {reference_parameters["version"]}:
        raise ValueError("dataset evaluation version does not match the reference parameter file")
    train_x, train_y = arrays(rows, "train")
    validation_x, validation_y = arrays(rows, "validation")
    baseline = np.ones(len(COMPONENTS))
    baseline_slope = calibrate(train_x @ baseline, train_y)
    weights = fit(train_x, train_y, baseline_slope, args.iterations, args.learning_rate,
                  args.regularization)
    candidate_slope = calibrate(train_x @ weights, train_y)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    version = args.version or datetime.now(UTC).strftime("hce-texel-%Y%m%dT%H%M%SZ")
    candidate = args.output_dir / "candidate.params"
    reference = args.output_dir / "reference.params"
    absolute_weights = write_parameters(candidate, version, weights, candidate_slope,
                                         reference_parameters)
    shutil.copy2(args.reference, reference)
    report = {"schema_version": 1, "method": "Texel-style logistic cross-entropy",
              "dataset": str(args.dataset), "version": version,
              "rows": {"train": len(train_y), "validation": len(validation_y)},
              "optimizer": {"iterations": args.iterations, "learning_rate": args.learning_rate,
                            "l2_toward_reference": args.regularization},
              "reference": {"parameters": str(reference),
                            "calibration_slope": baseline_slope,
                            "train": metrics(train_x, train_y, baseline, baseline_slope),
                            "validation": metrics(validation_x, validation_y, baseline,
                                                  baseline_slope)},
              "candidate": {"parameters": str(candidate), "multipliers_relative_to_reference": {
                                  name: float(value) for name, value in
                                  zip(COMPONENTS, weights, strict=True)},
                            "weights_per_mille": absolute_weights,
                            "calibration_slope": candidate_slope,
                            "train": metrics(train_x, train_y, weights, candidate_slope),
                            "validation": metrics(validation_x, validation_y, weights,
                                                  candidate_slope)}}
    report["validation_improved"] = (report["candidate"]["validation"]["log_loss"] <
                                     report["reference"]["validation"]["log_loss"])
    report_path = args.output_dir / "tuning.json"
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"candidate": str(candidate), "reference": str(reference),
                      "report": str(report_path),
                      "validation_improved": report["validation_improved"]}))


if __name__ == "__main__":
    main()
